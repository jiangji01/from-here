const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..');
const js=fs.readFileSync(path.join(root,'extension','sidepanel.js'),'utf8');
const html=fs.readFileSync(path.join(root,'extension','sidepanel.html'),'utf8');
const css=fs.readFileSync(path.join(root,'extension','sidepanel.css'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'extension','manifest.json'),'utf8'));
for(const token of ['activeJobId','/api/jobs/','lastGoodTrack','chrome.storage.local','renderJourney','展开其余','currentRelation','/api/session/keep','playbackOnly']) assert(js.includes(token),`UI contract missing ${token}`);
assert(!js.includes('查看后面的'),'old ambiguous queue copy remains');
for(const token of ['journey','progressBar','startState','routeAnchorTitle','routeCurrentTitle','routeAnchorLabel','routeCurrentLabel','sessionNotice','ambientArt']) assert(html.includes(`id="${token}"`),`HTML missing ${token}`);
for(const token of ['--blue:#1238c8','route-line','current-node','path-slider','ambient-art']) assert(css.includes(token),`Identity CSS missing ${token}`);
assert(html.includes('后面近一点'),'new future-only feedback copy missing');
assert(html.includes('多一点这个方向'),'new positive feedback copy missing');
assert.equal(manifest.version,require('./package.json').version);
for(const n of [16,32,48,128]) assert(fs.statSync(path.join(root,'extension','icons',`icon${n}.png`)).size>200,`icon${n} invalid`);
for(const f of ['github-hero.png','social-preview.png','demo.gif']) assert(fs.statSync(path.join(root,'brand',f)).size>500,`brand asset ${f} invalid`);
assert(fs.statSync(path.join(root,'brand','mark.svg')).size>200,'brand mark invalid');
assert(html.includes('结束这一轮'),'ambiguous end-session copy remains');
assert(!js.includes("api('/api/state')"),'UI must not merge independent playback snapshots');
assert(!js.includes('renderSession(job.result)'),'completed jobs must not flash stale playback snapshots');
assert(!js.includes('网易云召回，经过本轮边界重排'),'engineering-facing recommendation reason leaked into UI');
console.log('✓ UI identity: single playback truth + stable end state + compact origin + dismissed signal + human recommendation reasons');
