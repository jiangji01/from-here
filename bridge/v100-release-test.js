const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'extension','manifest.json'),'utf8'));
const pkg=JSON.parse(fs.readFileSync(path.join(__dirname,'package.json'),'utf8'));
const server=fs.readFileSync(path.join(__dirname,'server.js'),'utf8');
const readme=fs.readFileSync(path.join(root,'README.md'),'utf8');
const release=fs.readFileSync(path.join(root,'docs','RELEASE-v1.0.0.md'),'utf8');
const license=fs.readFileSync(path.join(root,'LICENSE'),'utf8');
const runtimeReadme=fs.readFileSync(path.join(root,'release-templates','README-FIRST.txt'),'utf8');
assert.equal(manifest.version,'1.0.0');
assert.equal(pkg.version,'1.0.0');
assert(server.includes("appVersion:'1.0.0'"),'Bridge health version must be 1.0.0');
assert(readme.includes('Jipeng Song / 宋吉鹏'),'README maker identity missing');
assert(readme.includes('jiangji628@gmail.com'),'README public email missing');
assert(readme.includes('https://nclcat.com'),'README blog missing');
assert(!readme.includes('Public Alpha'),'README must not describe 1.0 as Public Alpha');
assert(release.includes('From Here v1.0.0 — First public release'),'release notes title missing');
assert(license.includes('Jipeng Song and From Here contributors'),'license maintainer ownership missing');
assert(runtimeReadme.includes('v1.0.0'),'runtime README version missing');
console.log('✓ v1.0.0 release metadata + maintainer identity');
