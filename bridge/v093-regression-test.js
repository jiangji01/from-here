const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.join(__dirname,'..');
const server=fs.readFileSync(path.join(__dirname,'server.js'),'utf8');
const prompt=fs.readFileSync(path.join(__dirname,'prompts','music-semantic.js'),'utf8');
const ui=fs.readFileSync(path.join(root,'extension','sidepanel.js'),'utf8');
